#!/usr/bin/env python3
"""Validate and render the Bastion-Agent backlog.

Items live one per file under ``backlog/items/IDEA-NNN-<slug>.md`` and
``backlog/config.toml`` holds the phase governance, so a branch edits only the
file for the item it is working on and two branches never touch the same path.
``BACKLOG.md`` is a rendered index and is not tracked; ``--write`` refreshes it
locally so the board stays readable without putting generated content in git.

This script is the only writer of the rendered index and the only validator of
the item store. It deliberately mirrors scripts/check_adrs.py: deterministic,
offline, no third-party dependencies, non-zero exit on error.

Usage:
    uv run python scripts/check_backlog.py             # validate (default)
    uv run python scripts/check_backlog.py --write     # validate, then render BACKLOG.md
    uv run python scripts/check_backlog.py --next      # items that are ready to start
    uv run python scripts/check_backlog.py --next --json
    uv run python scripts/check_backlog.py --next-id   # the id a capture should take
    uv run python scripts/check_backlog.py --new "<title>"   # create the item file

Exit codes:
    0  valid (warnings allowed)
    1  validation errors
    2  the store is missing, unreadable or unwritable
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import sys
import tempfile
import tomllib
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

STATUSES = ("inbox", "ready", "active", "blocked", "done", "dropped")
PRIORITIES = ("P0", "P1", "P2", "P3")
AREAS = ("agent", "gateway", "db", "infra", "security", "evals", "docs", "tooling")
PHASES = ("v0.1", "v0.2", "v0.3", "v0.4", "v0.5", "v0.6")
DONE_STATES = {"done", "dropped"}

ITEMS_DIR = Path("backlog") / "items"
CONFIG_FILE = Path("backlog") / "config.toml"
INDEX_FILE = Path("BACKLOG.md")
ITEM_SUFFIX = ".md"

REQUIRED_FIELDS = (
    "status",
    "priority",
    "phase",
    "area",
    "tags",
    "depends-on",
    "spec",
    "created",
    "updated",
    "source",
)
REQUIRED_SECTIONS = ("Problem", "Outcome")
INBOX_MAX_AGE_DAYS = 14
MAX_TAGS = 6
MAX_FUZZY_RATIO = 0.90
TODO_SENTINEL = "TODO: fill"

SECTION_RE = re.compile("[*][*](Problem|Outcome)[.]?[*][*]", re.MULTILINE)
HEADING_RE = re.compile(r"^### (IDEA-\d{3}): (.+)$", re.MULTILINE)
FIELD_RE = re.compile(r"^- ([a-z][a-z-]*): (.*)$")
ACCEPTANCE_RE = re.compile(r"^\*\*Acceptance\*\*(.*?)(?=^\*\*|\Z)", re.MULTILINE | re.DOTALL)
CHECKBOX_RE = re.compile(r"^- \[([ xX])\]", re.MULTILINE)
TAG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
SPEC_RE = re.compile(r"^(?:ADR-\d{3}|ADR-Index|HANDOVER_SPEC|-)$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
NO_DEPS = {"", "-", "--", "none"}

INDEX_HEADER = """\
# BACKLOG - Bastion-Agent

Generated by `uv run python scripts/check_backlog.py --write` from
`backlog/items/*.md` and `backlog/config.toml`. Do not edit this file and do not
track it in git: it is an index, not a source. A new idea is one new file under
`backlog/items/`; `docs/adr/` records decisions and `HANDOVER_SPEC.md` records
the design.
"""


@dataclass
class Item:
    id: str
    title: str
    line: int
    body: str
    path: Path
    fields: dict[str, str] = field(default_factory=dict)
    acceptance: list[bool] = field(default_factory=list)

    @property
    def status(self) -> str:
        return self.fields.get("status", "")

    @property
    def priority(self) -> str:
        return self.fields.get("priority", "?")

    @property
    def phase(self) -> str:
        return self.fields.get("phase", "?")

    @property
    def deps(self) -> list[str]:
        raw = self.fields.get("depends-on", "")
        if raw.strip().lower() in NO_DEPS:
            return []
        return [part.strip() for part in raw.split(",") if part.strip()]


def parse_item(path: Path) -> Item:
    """Parse one item file. Raises ValueError when the file is not one item."""
    text = path.read_text(encoding="utf-8")
    headings = list(HEADING_RE.finditer(text))
    if not headings:
        raise ValueError("no '### IDEA-NNN: Title' heading")
    if len(headings) > 1:
        raise ValueError(f"{len(headings)} items in one file; split them into separate files")
    match = headings[0]
    body = text[match.end() :]

    fields: dict[str, str] = {}
    lines = body.splitlines()
    cursor = 0
    while cursor < len(lines) and not lines[cursor].strip():
        cursor += 1
    while cursor < len(lines):
        field_match = FIELD_RE.match(lines[cursor])
        if not field_match:
            break
        fields[field_match.group(1)] = field_match.group(2).strip()
        cursor += 1

    acceptance: list[bool] = []
    acceptance_match = ACCEPTANCE_RE.search(body)
    if acceptance_match:
        acceptance = [
            box.strip().lower() == "x" for box in CHECKBOX_RE.findall(acceptance_match.group(1))
        ]

    return Item(
        id=match.group(1),
        title=match.group(2).strip(),
        line=text.count("\n", 0, match.start()) + 1,
        body=body,
        path=path,
        fields=fields,
        acceptance=acceptance,
    )


def load(root: Path) -> tuple[dict[str, str], list[Item], list[str]]:
    """Read the config and every item file. Returns (meta, items, load errors)."""
    errors: list[str] = []
    meta: dict[str, str] = {}
    config_path = root / CONFIG_FILE
    if not config_path.is_file():
        errors.append(f"meta: {CONFIG_FILE} is missing")
    else:
        try:
            config = tomllib.loads(config_path.read_text(encoding="utf-8"))
        except (tomllib.TOMLDecodeError, OSError) as error:
            errors.append(f"meta: {CONFIG_FILE}: {error}")
            config = {}
        for key in ("current-phase", "wip-limit"):
            if key not in config:
                errors.append(f"meta: {CONFIG_FILE} is missing '{key}'")
            else:
                meta[key] = str(config[key])

    items: list[Item] = []
    items_dir = root / ITEMS_DIR
    if not items_dir.is_dir():
        errors.append(f"items: {ITEMS_DIR} is missing")
        return meta, items, errors

    for path in sorted(items_dir.glob(f"*{ITEM_SUFFIX}")):
        try:
            item = parse_item(path)
        except (ValueError, OSError) as error:
            errors.append(f"{path.name}: {error}")
            continue
        if not path.name.startswith(f"{item.id}-"):
            errors.append(f"{path.name}: filename must start with '{item.id}-'")
        items.append(item)

    items.sort(key=lambda item: item.id)
    return meta, items, errors


def find_cycle(graph: dict[str, list[str]]) -> list[str] | None:
    state: dict[str, int] = {}
    stack: list[str] = []

    def visit(node: str) -> list[str] | None:
        status = state.get(node, 0)
        if status == 1:
            return [*stack[stack.index(node) :], node]
        if status == 2:
            return None
        state[node] = 1
        stack.append(node)
        for dep in graph.get(node, []):
            if dep in graph:
                cycle = visit(dep)
                if cycle:
                    return cycle
        stack.pop()
        state[node] = 2
        return None

    for node in graph:
        cycle = visit(node)
        if cycle:
            return cycle
    return None


def normalize_title(title: str) -> str:
    return " ".join(re.sub(r"[^a-z0-9 ]+", " ", title.lower()).split())


def validate(
    meta: dict[str, str], items: list[Item], load_errors: list[str] | None = None
) -> tuple[list[str], list[str]]:
    errors: list[str] = list(load_errors or [])
    warnings: list[str] = []

    current_phase = meta.get("current-phase", "")
    if current_phase and current_phase not in PHASES:
        errors.append(f"meta: current-phase '{current_phase}' is not one of {', '.join(PHASES)}")
    try:
        wip_limit = int(meta.get("wip-limit", "3"))
        if wip_limit < 1:
            raise ValueError
    except ValueError:
        errors.append("meta: wip-limit must be a positive integer")
        wip_limit = 3

    if not items:
        errors.append(f"no items: expected at least one file under {ITEMS_DIR}")

    seen_ids: set[str] = set()
    for item in items:
        where = f"{item.id} ({item.path.name}:{item.line})"
        if item.id in seen_ids:
            errors.append(
                f"{where}: duplicate id; two branches allocated the same number, "
                f"rename one file with 'git mv' and update any depends-on"
            )
        seen_ids.add(item.id)

        for key in REQUIRED_FIELDS:
            if key not in item.fields:
                errors.append(f"{where}: missing field '{key}'")
        present = {match.group(1) for match in SECTION_RE.finditer(item.body)}
        for section in REQUIRED_SECTIONS:
            if section not in present:
                errors.append(f"{where}: missing '{section}' section")
        if TODO_SENTINEL in item.body:
            errors.append(f"{where}: unfinished skeleton ('{TODO_SENTINEL}' still present)")

        if item.status and item.status not in STATUSES:
            errors.append(f"{where}: status '{item.status}' is not one of {', '.join(STATUSES)}")
        if item.priority and item.priority not in PRIORITIES:
            errors.append(
                f"{where}: priority '{item.priority}' is not one of {', '.join(PRIORITIES)}"
            )
        if item.phase and item.phase not in PHASES:
            errors.append(f"{where}: phase '{item.phase}' is not one of {', '.join(PHASES)}")
        area = item.fields.get("area", "")
        if area and area not in AREAS:
            errors.append(f"{where}: area '{area}' is not one of {', '.join(AREAS)}")

        tags_raw = item.fields.get("tags", "")
        if tags_raw and tags_raw != "-":
            tags = [tag.strip() for tag in tags_raw.split(",") if tag.strip()]
            if not tags:
                errors.append(f"{where}: tags must be a comma-separated list or '-'")
            if len(tags) > MAX_TAGS:
                errors.append(f"{where}: {len(tags)} tags (maximum {MAX_TAGS})")
            for tag in tags:
                if not TAG_RE.match(tag):
                    errors.append(f"{where}: tag '{tag}' must be lowercase kebab-case")
            if len(set(tags)) != len(tags):
                errors.append(f"{where}: duplicate tag")

        spec = item.fields.get("spec", "")
        if spec and not SPEC_RE.match(spec):
            errors.append(
                f"{where}: spec '{spec}' must be ADR-NNN, ADR-Index, HANDOVER_SPEC or '-'"
            )

        created_raw = item.fields.get("created", "")
        updated_raw = item.fields.get("updated", "")
        created = updated = None
        for label, value in (("created", created_raw), ("updated", updated_raw)):
            if not value:
                continue
            if not DATE_RE.match(value):
                errors.append(f"{where}: {label} '{value}' must be YYYY-MM-DD")
                continue
            try:
                parsed = date.fromisoformat(value)
            except ValueError:
                errors.append(f"{where}: {label} '{value}' is not a real date")
                continue
            if label == "created":
                created = parsed
            else:
                updated = parsed
        if created and updated and updated < created:
            errors.append(f"{where}: updated {updated_raw} is before created {created_raw}")

        for dep in item.deps:
            if not re.match(r"^IDEA-\d{3}$", dep):
                errors.append(f"{where}: depends-on '{dep}' must be IDEA-NNN")
            elif dep == item.id:
                errors.append(f"{where}: depends on itself")
            elif dep not in {other.id for other in items}:
                errors.append(f"{where}: depends-on '{dep}' does not exist")

        if item.status in ("ready", "active"):
            unresolved = [
                dep
                for dep in item.deps
                if next((other.status for other in items if other.id == dep), "missing")
                not in DONE_STATES
            ]
            if unresolved:
                errors.append(
                    f"{where}: status '{item.status}' but blocked by {', '.join(unresolved)}"
                )
            if current_phase and item.phase > current_phase:
                warnings.append(
                    f"{where}: {item.phase} work marked '{item.status}' while current phase is "
                    f"{current_phase}"
                )

        if item.status == "blocked" and not item.fields.get("blocked-by"):
            errors.append(f"{where}: status 'blocked' requires a 'blocked-by' field")

        if item.status == "done":
            if not item.acceptance:
                errors.append(f"{where}: status 'done' needs an **Acceptance** checklist")
            unchecked = sum(1 for checked in item.acceptance if not checked)
            if unchecked:
                errors.append(
                    f"{where}: status 'done' with {unchecked} unchecked acceptance box(es)"
                )

        if item.status == "inbox" and created:
            age = (date.today() - created).days
            if age > INBOX_MAX_AGE_DAYS:
                warnings.append(f"{where}: untriaged inbox item is {age} days old")

    ids = {item.id for item in items}
    graph = {item.id: [dep for dep in item.deps if dep in ids] for item in items}
    cycle = find_cycle(graph)
    if cycle:
        errors.append(f"dependency cycle: {' -> '.join(cycle)}")

    titles: dict[str, str] = {}
    for item in items:
        normalized = normalize_title(item.title)
        if normalized in titles:
            errors.append(f"{item.id}: duplicate title of {titles[normalized]}")
            continue
        titles[normalized] = item.id

    for index, item in enumerate(items):
        for other in items[index + 1 :]:
            if normalize_title(item.title) == normalize_title(other.title):
                continue
            ratio = difflib.SequenceMatcher(
                None, normalize_title(item.title), normalize_title(other.title)
            ).ratio()
            if ratio >= MAX_FUZZY_RATIO:
                warnings.append(
                    f"{item.id}: title is {ratio:.0%} similar to {other.id}; check for duplicates"
                )

    numeric = sorted(int(item.id.split("-")[1]) for item in items)
    if numeric:
        gaps = [
            f"IDEA-{number:03d}"
            for number in range(numeric[0], numeric[-1])
            if number not in numeric
        ]
        if gaps:
            warnings.append(f"meta: id gap at {', '.join(gaps)} (dropped ids keep their number)")

    active = [item for item in items if item.status == "active"]
    if len(active) > wip_limit:
        warnings.append(
            f"{len(active)} items are 'active' but wip-limit is {wip_limit}: "
            f"{', '.join(item.id for item in active)}"
        )

    return errors, warnings


def render_board(meta: dict[str, str], items: list[Item]) -> str:
    lines: list[str] = []
    for status in STATUSES:
        group = [item for item in items if item.status == status]
        if status in ("dropped",) and not group:
            continue
        lines.append(f"### {status.capitalize()} ({len(group)})")
        lines.append("")
        if not group:
            lines.append("_none_")
        else:
            for item in group:
                suffix = ""
                if item.deps:
                    suffix = f" (waiting on {', '.join(item.deps)})"
                lines.append(
                    f"- `{item.id}` {item.priority} {item.phase} {item.fields.get('area', '?')}"
                    f" - {item.title}{suffix}"
                )
        lines.append("")
    phase = meta.get("current-phase", "?")
    lines.append(
        f"_Phase gate: {phase} - items at or below it may start; later phases stay parked._"
    )
    return "\n".join(lines).rstrip() + "\n"


def render_index(items: list[Item]) -> str:
    lines = [
        "| ID | Status | Prio | Phase | Area | Title |",
        "|---|---|---|---|---|---|",
    ]
    for item in items:
        lines.append(
            f"| {item.id} | {item.status or '?'} | {item.priority} | {item.phase} "
            f"| {item.fields.get('area', '?')} | {item.title} |"
        )
    return "\n".join(lines) + "\n"


def render(meta: dict[str, str], items: list[Item]) -> str:
    board = render_board(meta, items)
    index = render_index(items)
    return f"{INDEX_HEADER}\n## Board\n\n{board}\n## Index\n\n{index}"


def write_atomic(path: Path, text: str) -> None:
    """Replace ``path`` in one step so a crash cannot leave a truncated index."""
    handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def next_id(items: list[Item]) -> str:
    numeric = [int(item.id.split("-")[1]) for item in items]
    return f"IDEA-{max(numeric) + 1 if numeric else 1:03d}"


def slugify(title: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:48].strip("-")
    return slug or "item"


def create_item(root: Path, meta: dict[str, str], items: list[Item], title: str) -> Path:
    """Create the next item file, failing rather than overwriting an existing one."""
    item_id = next_id(items)
    path = root / ITEMS_DIR / f"{item_id}-{slugify(title)}{ITEM_SUFFIX}"
    today = date.today().isoformat()
    body = f"""\
### {item_id}: {title}

- status: inbox
- priority: P2
- phase: {meta.get("current-phase", "v0.1")}
- area: -
- tags: -
- depends-on: -
- spec: -
- created: {today}
- updated: {today}
- source: session

**Problem**

{TODO_SENTINEL}

**Outcome**

{TODO_SENTINEL}

**Acceptance**

- [ ] {TODO_SENTINEL}
"""
    handle = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
    with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(body)
    return path


def ready_items(meta: dict[str, str], items: list[Item]) -> list[Item]:
    current_phase = meta.get("current-phase", "")
    by_id = {item.id: item for item in items}
    ready: list[Item] = []
    for item in items:
        if item.status != "ready":
            continue
        if item.deps and any(
            by_id[dep].status not in DONE_STATES for dep in item.deps if dep in by_id
        ):
            continue
        if current_phase and item.phase > current_phase:
            continue
        ready.append(item)
    return sorted(ready, key=lambda item: (PRIORITIES.index(item.priority), item.id))


def print_summary(meta: dict[str, str], items: list[Item]) -> None:
    counts = ", ".join(
        f"{status} {sum(1 for item in items if item.status == status)}" for status in STATUSES
    )
    print(f"OK: {len(items)} items ({counts}); phase {meta.get('current-phase', '?')}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--root",
        default=None,
        type=Path,
        help="repository root holding backlog/ (default: this script's parent)",
    )
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="validate only (default)")
    group.add_argument("--write", action="store_true", help="validate, then render BACKLOG.md")
    group.add_argument("--next", dest="list_next", action="store_true", help="list ready items")
    group.add_argument(
        "--next-id", action="store_true", help="print the id the next capture should take"
    )
    group.add_argument(
        "--new", metavar="TITLE", help="create the next item file and print its path"
    )
    parser.add_argument("--json", action="store_true", help="machine-readable output for --next")
    parser.add_argument("--quiet", action="store_true", help="suppress warnings")
    args = parser.parse_args(argv)

    root = args.root if args.root else Path(__file__).resolve().parents[1]
    meta, items, load_errors = load(root)

    if args.next_id:
        if load_errors:
            for error in load_errors:
                print(f"error: {error}", file=sys.stderr)
            return 2
        print(next_id(items))
        return 0

    if args.new:
        if load_errors:
            for error in load_errors:
                print(f"error: {error}", file=sys.stderr)
            return 2
        try:
            path = create_item(root, meta, items, args.new)
        except FileExistsError as exists:
            print(
                f"error: {exists.filename} already exists; retry to take the next id",
                file=sys.stderr,
            )
            return 1
        except OSError as failure:
            print(f"error: {failure}", file=sys.stderr)
            return 2
        print(path)
        print(
            f"fill in area, tags, spec, Problem, Outcome and Acceptance, then run "
            f"{Path(__file__).name} --check",
            file=sys.stderr,
        )
        return 0

    errors, warnings = validate(meta, items, load_errors)
    if not args.quiet:
        for warning in warnings:
            print(f"warning: {warning}", file=sys.stderr)
    for error in errors:
        print(f"error: {error}", file=sys.stderr)

    if args.list_next:
        if errors:
            print("error: fix validation errors before asking for ready work", file=sys.stderr)
            return 1
        ready = ready_items(meta, items)
        if args.json:
            print(
                json.dumps(
                    {
                        "phase": meta.get("current-phase"),
                        "items": [
                            {
                                "id": item.id,
                                "title": item.title,
                                "priority": item.priority,
                                "phase": item.phase,
                                "area": item.fields.get("area"),
                                "depends_on": item.deps,
                            }
                            for item in ready
                        ],
                    },
                    indent=2,
                )
            )
        else:
            if not ready:
                print("no ready items")
            for item in ready:
                deps = ", ".join(item.deps) if item.deps else "-"
                area = item.fields.get("area", "?")
                columns = (item.id, item.priority, item.phase, f"{area:<8}", item.title)
                print("  ".join(columns) + f"  [deps: {deps}]")
        return 0

    if errors:
        return 1

    if args.write:
        rendered = render(meta, items)
        index = root / INDEX_FILE
        if index.is_file() and index.read_text(encoding="utf-8") == rendered:
            print(f"{INDEX_FILE}: already current")
        else:
            write_atomic(index, rendered)
            print(f"rendered {INDEX_FILE}")

    print_summary(meta, items)
    return 0


if __name__ == "__main__":
    sys.exit(main())
